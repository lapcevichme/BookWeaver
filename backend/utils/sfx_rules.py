"""
Звуковые эффекты по явным действиям в тексте — без LLM.

Раньше SFX выбирала LLM вместе с эмбиентом: с reasoning это половина всего LLM-времени книги
(1416 из 2834 с на Кусурии, `cli.py inspect cost`), без reasoning — притянутые звуки
(`pour_liquid` на «пила из чашки», `laugh_crowd` на смех одного человека;
docs/experiments/2026-11-06_reasoning-by-stage.md). Правило не фантазирует: нет действия в тексте —
нет эффекта. Применяется к словам автора (narration): в репликах звук не описывается.

Порядок важен: первое совпадение побеждает (хлопок дверью раньше, чем «закрыл дверь»).
"""
import re
from typing import Iterable, List, Optional, Tuple

_D = r"двер\w*"  # дверь, двери, дверью
_RULES: List[Tuple[str, str]] = [
    ("door_knock", rf"постуча\w*(?:\s+\w+){{0,2}}\s+в\s+{_D}|стук\w*\s+в\s+{_D}|\bв\s+{_D}\s+постучал\w*"),
    ("door_slam", rf"хлопну\w*\s+{_D}|{_D}\s+(?:с\s+грохотом\s+)?(?:захлопнул\w*|хлопнул\w*)|захлопну\w*\s+{_D}"),
    ("door_close_wood", rf"\bзакры\w*(?:\s+за\s+собой)?\s+{_D}|{_D}\s+(?:за\s+\w+\s+)?закры\w*"),
    ("door_open_wood", rf"\b(?:откры|распахну|отвори)\w*\s+{_D}|{_D}\s+(?:со\s+скрипом\s+)?(?:откры|распахну|отвори)\w*"),
    ("thunder_clap", r"раскат\w*\s+грома|гром\w*\s+(?:грянул|прогремел|ударил)|(?:грянул|прогремел)\w*\s+гром"),
    ("explosion_distant", r"\bвзрыв\w*|\bвзорвал\w*"),
    ("horse_neigh", r"\bзаржал\w*|\bржани\w*|\bржал[аи]?\b"),
    ("sword_clash", r"скрести\w*\s+(?:мечи|клинки|сабли)|звон\w*\s+(?:мечей|клинков|стали)|(?:мечи|клинки)\s+скрестил\w*"),
    ("sword_draw", r"(?:выхватил|обнажил|вынул|извлек)\w*\s+(?:из\s+ножен\s+)?(?:меч|клинок|саблю|шпагу)"),
    ("glass_break", r"(?:разбил|разбила|разлетел|раскол)\w*\s+(?:\w+\s+)?(?:бокал|стакан|стекл|чаш|кувшин|окн)\w*"
                    r"|(?:бокал|стакан|чаш|кувшин|стекл)\w*\s+(?:разбил|разлетел|треснул|раскол)\w*"),
    ("punch_hit", r"удари\w*\s+(?:\w+\s+)?кулак\w*|кулак\w*\s+(?:в|по)\s+\w+|\bврезал\w*|ударил\w*\s+по\s+(?:лицу|щеке|челюсти)"),
    ("body_fall", r"\bрухну\w*|упал\w*\s+(?:на\s+(?:землю|пол|колени)|замертво|без\s+чувств)|повалил\w*\s+на\s+(?:землю|пол)"),
    ("pour_liquid", r"\b(?:нали|подли|разли|плесну)\w*|\bналива\w*"),
    ("paper_rustle", r"(?:разверну|развернул|сложил|сверну|перелистну|листал)\w*\s+(?:\w+\s+)?(?:записк|письм|бумаг|свит|лист)\w*"
                     r"|шурш\w*\s+(?:бумаг|страниц|лист)\w*|(?:бумаг|страниц|лист)\w*\s+зашуршал\w*"),
    ("coin_drop", r"звон\w*\s+монет|(?:бросил|швырнул|высыпал|звякну)\w*\s+(?:\w+\s+)?(?:монет|медяк|серебрян)\w*"),
    ("applaud", r"\bаплодир\w*|\bрукоплеска\w*|\bзахлопали\b|\bаплодисмент\w*"),
    ("laugh_crowd", r"(?:толпа|зал|все|присутствующие|гости|служанки)\s+(?:\w+\s+)?(?:рассмеял|расхохотал|засмеял|захохотал)\w*"
                    r"|смех\s+толпы|хохот\s+(?:толпы|зала)"),
    ("magic_cast", r"(?:произнес|сотворил|прочел|прочла)\w*\s+заклина\w*|заклина\w*\s+(?:сорвал|вспыхнул|прозвучал)\w*"),
    ("gasp_female", r"\bахнула\b|\bвскрикнула\b|\bохнула\b"),
    ("gasp_male", r"\bахнул\b|\bвскрикнул\b|\bохнул\b"),
    ("footsteps_wood_fast", r"\b(?:побежал|побежала|бросил\w*\s+бежать|помчал\w*|кинул\w*\s+бежать)\b"),
    ("footsteps_stone", r"шаг\w*\s+(?:по\s+)?(?:камн|брусчат|мостов)\w*|по\s+(?:брусчатке|мостовой)"),
    ("footsteps_grass", r"шаг\w*\s+по\s+трав\w*|по\s+траве"),
]
RULES = [(sfx, re.compile(pattern, re.IGNORECASE)) for sfx, pattern in _RULES]


def pick_sfx(text: str, available: Optional[Iterable[str]] = None) -> Optional[str]:
    """Эффект для текста или None. available — id из библиотеки (чего нет в библиотеке, не выдаем)."""
    if not text:
        return None
    allowed = set(available) if available is not None else None
    for sfx, rx in RULES:
        if (allowed is None or sfx in allowed) and rx.search(text):
            return sfx
    return None
